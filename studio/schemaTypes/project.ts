import {defineArrayMember, defineField, defineType} from 'sanity'

const requiredText = (title: string, name: string, group: string) =>
  defineField({
    name,
    title,
    type: 'string',
    group,
    validation: (rule) => rule.required(),
  })

export const project = defineType({
  name: 'project',
  title: 'Completed project',
  type: 'document',
  groups: [
    {name: 'overview', title: 'Overview', default: true},
    {name: 'story', title: 'Story'},
    {name: 'features', title: 'Systems and features'},
    {name: 'gallery', title: 'Gallery'},
    {name: 'outcome', title: 'Outcome and call to action'},
    {name: 'seo', title: 'Search details'},
  ],
  fields: [
    requiredText('Project name', 'title', 'overview'),
    defineField({
      name: 'slug',
      title: 'Page address',
      type: 'slug',
      group: 'overview',
      description: 'Use Generate when adding a new project. Avoid changing this after publishing.',
      options: {source: 'title', maxLength: 70},
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'order',
      title: 'Display order',
      type: 'number',
      group: 'overview',
      description: 'Lower numbers appear first on the Our Work page.',
      initialValue: 50,
      validation: (rule) => rule.required().integer().min(0),
    }),
    defineField({name: 'projectType', title: 'Project type', type: 'string', group: 'overview'}),
    defineField({name: 'location', title: 'Location', type: 'string', group: 'overview'}),
    defineField({
      name: 'cardSummary',
      title: 'Our Work summary',
      type: 'text',
      rows: 4,
      group: 'overview',
      validation: (rule) => rule.required().max(500),
    }),
    defineField({
      name: 'award',
      title: 'Award label',
      type: 'string',
      group: 'overview',
      description: 'Optional. Shown over the project image.',
    }),
    requiredText('Normal part of page heading', 'heroTitleBefore', 'overview'),
    defineField({
      name: 'heroTitleEmphasis',
      title: 'Highlighted ending',
      type: 'string',
      group: 'overview',
    }),
    defineField({name: 'heroTitleAfter', title: 'Text after highlighted words', type: 'string', group: 'overview'}),
    defineField({
      name: 'heroSummary',
      title: 'Opening summary',
      type: 'text',
      rows: 4,
      group: 'overview',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'heroImage',
      title: 'Main image',
      type: 'image',
      group: 'overview',
      options: {hotspot: true},
      fields: [
        defineField({
          name: 'alt',
          title: 'Image description',
          type: 'string',
          description: 'Describe what is visible for accessibility and search.',
          validation: (rule) => rule.required(),
        }),
      ],
      validation: (rule) => rule.required(),
    }),
    defineField({name: 'heroCreditLabel', title: 'Main image credit', type: 'string', group: 'overview'}),
    defineField({name: 'heroCreditUrl', title: 'Main image credit link', type: 'url', group: 'overview'}),
    defineField({
      name: 'facts',
      title: 'Quick facts',
      type: 'array',
      group: 'overview',
      validation: (rule) => rule.max(4),
      of: [
        defineArrayMember({
          type: 'object',
          name: 'fact',
          fields: [
            defineField({name: 'label', title: 'Label', type: 'string', validation: (rule) => rule.required()}),
            defineField({name: 'value', title: 'Value', type: 'string', validation: (rule) => rule.required()}),
          ],
          preview: {select: {title: 'label', subtitle: 'value'}},
        }),
      ],
    }),
    defineField({name: 'storyKicker', title: 'Small heading', type: 'string', group: 'story'}),
    requiredText('Story heading', 'storyHeadingBefore', 'story'),
    defineField({name: 'storyHeadingEmphasis', title: 'Highlighted ending', type: 'string', group: 'story'}),
    defineField({name: 'storyHeadingAfter', title: 'Text after highlighted words', type: 'string', group: 'story'}),
    defineField({
      name: 'storyParagraphs',
      title: 'Project story',
      type: 'array',
      group: 'story',
      of: [defineArrayMember({type: 'text', rows: 4})],
      validation: (rule) => rule.required().min(1),
    }),
    defineField({name: 'featuresHeading', title: 'Section heading', type: 'string', group: 'features'}),
    defineField({name: 'featuresSummary', title: 'Section summary', type: 'text', rows: 3, group: 'features'}),
    defineField({
      name: 'features',
      title: 'Systems and features',
      type: 'array',
      group: 'features',
      of: [
        defineArrayMember({
          type: 'object',
          name: 'feature',
          fields: [
            defineField({name: 'title', title: 'Title', type: 'string', validation: (rule) => rule.required()}),
            defineField({name: 'description', title: 'Description', type: 'text', rows: 4, validation: (rule) => rule.required()}),
          ],
          preview: {select: {title: 'title', subtitle: 'description'}},
        }),
      ],
    }),
    defineField({name: 'galleryHeading', title: 'Small heading', type: 'string', group: 'gallery'}),
    defineField({name: 'gallerySummary', title: 'Gallery introduction', type: 'text', rows: 3, group: 'gallery'}),
    defineField({
      name: 'gallery',
      title: 'Project images',
      type: 'array',
      group: 'gallery',
      options: {layout: 'grid'},
      validation: (rule) => rule.required().min(1),
      of: [
        defineArrayMember({
          type: 'object',
          name: 'galleryImage',
          fields: [
            defineField({name: 'image', title: 'Image', type: 'image', options: {hotspot: true}, validation: (rule) => rule.required()}),
            defineField({name: 'alt', title: 'Image description', type: 'string', validation: (rule) => rule.required()}),
            defineField({name: 'caption', title: 'Caption', type: 'string'}),
            defineField({
              name: 'wide',
              title: 'Use wide layout',
              type: 'boolean',
              initialValue: false,
            }),
          ],
          preview: {select: {title: 'caption', subtitle: 'alt', media: 'image'}},
        }),
      ],
    }),
    defineField({name: 'galleryCreditLabel', title: 'Gallery credit', type: 'string', group: 'gallery'}),
    defineField({name: 'galleryCreditUrl', title: 'Gallery credit link', type: 'url', group: 'gallery'}),
    defineField({name: 'outcomeQuoteBefore', title: 'Outcome quote', type: 'string', group: 'outcome'}),
    defineField({name: 'outcomeQuoteEmphasis', title: 'Highlighted ending', type: 'string', group: 'outcome'}),
    defineField({name: 'outcomeQuoteAfter', title: 'Text after highlighted words', type: 'string', group: 'outcome'}),
    defineField({name: 'outcomeBody', title: 'Outcome text', type: 'text', rows: 4, group: 'outcome'}),
    defineField({name: 'outcomeCredit', title: 'Outcome credit', type: 'string', group: 'outcome'}),
    defineField({name: 'ctaEyebrow', title: 'Call-to-action label', type: 'string', group: 'outcome'}),
    defineField({name: 'ctaTitleBefore', title: 'Call-to-action heading', type: 'string', group: 'outcome'}),
    defineField({name: 'ctaTitleEmphasis', title: 'Highlighted ending', type: 'string', group: 'outcome'}),
    defineField({name: 'ctaTitleAfter', title: 'Text after highlighted words', type: 'string', group: 'outcome'}),
    defineField({name: 'ctaBody', title: 'Call-to-action text', type: 'text', rows: 3, group: 'outcome'}),
    defineField({name: 'ctaButton', title: 'Button wording', type: 'string', group: 'outcome', initialValue: 'Free consultation'}),
    defineField({name: 'seoTitle', title: 'Search title', type: 'string', group: 'seo', validation: (rule) => rule.max(70)}),
    defineField({name: 'seoDescription', title: 'Search description', type: 'text', rows: 3, group: 'seo', validation: (rule) => rule.max(170)}),
  ],
  orderings: [
    {title: 'Website order', name: 'websiteOrder', by: [{field: 'order', direction: 'asc'}]},
    {title: 'Newest edited', name: 'updatedAt', by: [{field: '_updatedAt', direction: 'desc'}]},
  ],
  preview: {
    select: {title: 'title', subtitle: 'location', media: 'heroImage'},
  },
})
